"""Resolve legacy wiki links such as ``Old name#Material``.

A link is kept exactly as it was supplied, while the resolver follows the
redirect information returned by the wiki.  Redirects may add, replace or
preserve a fragment, so the effective section is tracked separately from the
page title.  A resolved section link returns only the referenced section; the
full page is never returned as a substitute for a section link.

The resolver distinguishes these outcomes:

``resolved``
    The target page and section were found.
``section_numbered``
    The target was a repeated heading and the link used the numbered anchor
    generated by MediaWiki (for example ``Material_2``).
``section_ambiguous``
    Several sections display exactly the same heading and the link did not
    identify which one.  All candidates (and their texts, if requested) are
    returned instead of silently taking the first one.
``section_deleted``
    The target page exists but the requested section does not.
``section_unavailable``
    The section index could not be read (for example because both the parse
    and revision APIs were refused), so no claim is made about existence.
``redirect_loop``
    Following redirects revisited a page/fragment state.
``page_missing``
    The target page does not exist.
``invalid``
    The supplied value is not an internal wiki link.
``redirect_unresolved``
    The page is marked as a redirect but the source did not return a usable
    redirect target.
"""

import re
import unicodedata
from dataclasses import dataclass, field
from html import unescape
from typing import Any, Dict, Iterable, List, Mapping, Optional, Tuple, TYPE_CHECKING
from urllib.parse import unquote

import mwclient.errors
import mwclient.page

if TYPE_CHECKING:
    import mwclient.client


STATUS_RESOLVED = 'resolved'
STATUS_SECTION_NUMBERED = 'section_numbered'
STATUS_SECTION_AMBIGUOUS = 'section_ambiguous'
STATUS_SECTION_DELETED = 'section_deleted'
STATUS_SECTION_UNAVAILABLE = 'section_unavailable'
STATUS_REDIRECT_LOOP = 'redirect_loop'
STATUS_PAGE_MISSING = 'page_missing'
STATUS_INVALID = 'invalid'
STATUS_REDIRECT_UNRESOLVED = 'redirect_unresolved'

#: Statuses for which :attr:`ResolvedLink.section` points at usable content.
RESOLVED_STATUSES = frozenset({STATUS_RESOLVED, STATUS_SECTION_NUMBERED})

_REDIRECT_RE = re.compile(
    r'^\s*#\s*redirect\s*:?\s*\[\[\s*([^\]\|#]+?)\s*(?:#\s*([^\]\|]*?)\s*)?'
    r'(?:\|[^\]]*)?\]\]',
    re.IGNORECASE | re.MULTILINE,
)
_EXTERNAL_RE = re.compile(r'^[a-z][a-z0-9+.-]*://', re.IGNORECASE)
_DUPLICATE_SUFFIX_RE = re.compile(r'_(?P<number>[2-9][0-9]*)$')
_HEADING_RE = re.compile(r'^(={1,6})\s*(.+?)\s*\1\s*$', re.MULTILINE)


def _slugify(heading: str) -> str:
    """Approximate MediaWiki's anchor generation for a heading."""
    value = re.sub(r'<[^>]+>', '', heading)
    value = unescape(value)
    value = _clean(value)
    value = value.replace(' ', '_')
    return value or 'section'


def _clean(value: Optional[str]) -> str:
    """Normalize text for comparison while preserving case.

    MediaWiki writes spaces in anchors as underscores and percent-encodes
    characters in URLs.  Headings may additionally contain HTML entities.
    """
    if value is None:
        return ''
    value = unescape(unquote(value))
    value = unicodedata.normalize('NFC', value)
    value = value.replace('_', ' ')
    value = re.sub(r'\s+', ' ', value)
    return value.strip()


def _normalize_title(title: str) -> str:
    """Return a comparison key for a page title."""
    return _clean(title).casefold()


def _decode_fragment(fragment: Optional[str]) -> Optional[str]:
    if fragment is None:
        return None
    fragment = unquote(fragment).strip()
    return fragment or None


@dataclass(frozen=True)
class RedirectHop:
    """One step in a redirect chain.

    Attributes:
        from_title: The title of the redirect page.
        to_title: The title named by the redirect (without its fragment).
        to_fragment: The fragment explicitly named by the redirect, if any.
            When this is ``None``, a fragment from the original link remains
            in effect, matching how MediaWiki follows section redirects.
    """

    from_title: str
    to_title: str
    to_fragment: Optional[str] = None

    @property
    def source(self) -> str:
        """Alias for :attr:`from_title`."""
        return self.from_title

    @property
    def target(self) -> str:
        """Alias for :attr:`to_title`."""
        return self.to_title


@dataclass(frozen=True)
class Section:
    """A section entry as returned by ``action=parse&prop=sections``.

    Attributes:
        page_title: The title of the page containing the section.
        index: The section index accepted by :meth:`mwclient.page.Page.text`.
        heading: The heading text as displayed (the API's ``line`` field).
        anchor: The canonical fragment for the heading, e.g. ``Material_2``.
        level: The heading level reported by the API.
        toclevel: The table-of-contents nesting level.
        number: The section number reported by the API, if any.
        byteoffset: Offset of the section in the page source, if reported.
        duplicate_number: For a repeated heading, the numeric suffix used in
            the anchor (2 for ``Material_2``), otherwise ``None``.
        duplicate_count: How many sections display exactly this heading.
        parents: Headings of the enclosing sections, outermost first.  This
            distinguishes identical headings in different parts of a page.
    """

    page_title: str
    index: int
    heading: str
    anchor: str
    level: int = 0
    toclevel: int = 0
    number: Optional[str] = None
    byteoffset: Optional[int] = None
    duplicate_number: Optional[int] = None
    duplicate_count: int = 1
    parents: Tuple[str, ...] = ()

    @property
    def line(self) -> str:
        """Alias for :attr:`heading`, matching the MediaWiki API field."""
        return self.heading

    @property
    def display(self) -> str:
        """The heading text shown to readers."""
        return self.heading

    @property
    def is_duplicate(self) -> bool:
        """Whether another section on the page has the same heading."""
        return self.duplicate_count > 1

    @property
    def is_numbered(self) -> bool:
        """Whether this is a repeated heading with a numbered anchor."""
        return self.duplicate_number is not None

    @property
    def path(self) -> Tuple[str, ...]:
        """The enclosing headings plus this heading."""
        return self.parents + (self.heading,)

    @property
    def parent(self) -> Optional[str]:
        """The immediately enclosing heading, if any."""
        return self.parents[-1] if self.parents else None


@dataclass(frozen=True)
class ResolvedLink:
    """The outcome of resolving one legacy link.

    Attributes:
        original: The link exactly as it was supplied.
        title: The page title written in the original link.
        fragment: The fragment written in the original link, URL-decoded.
        target_title: The page title after following redirects.
        target_fragment: The effective fragment after following redirects.
        status: One of the ``STATUS_*`` constants in this module.
        chain: Redirect hops in the order they were followed.
        section: The selected section when the outcome is unambiguous and
            usable, otherwise ``None``.
        candidates: All sections that display the requested heading when the
            target is ambiguous.  Empty in other outcomes.
        text: Wikitext of the selected section.  For an ambiguous target this
            is ``None``; see :attr:`texts` instead.
        texts: Wikitext for each entry of :attr:`candidates`, in the same
            order.  This is populated for ambiguous targets so that callers
            do not have to accept the first candidate as the answer.
        cycle: The repeated page titles forming a redirect loop, if any.
        reason: A short human-readable explanation for non-resolved outcomes.
        text_error: Why the section text could not be read, if independent of
            whether the section exists.
        page: A :class:`mwclient.page.Page` for the target page, if known.
        page_info: Raw page information returned by the API, if available.
    """

    original: str
    title: str
    fragment: Optional[str]
    target_title: Optional[str]
    target_fragment: Optional[str]
    status: str
    chain: Tuple[RedirectHop, ...] = ()
    section: Optional[Section] = None
    candidates: Tuple[Section, ...] = ()
    text: Optional[str] = None
    texts: Tuple[str, ...] = ()
    cycle: Tuple[str, ...] = ()
    reason: Optional[str] = None
    text_error: Optional[str] = None
    page: Optional['mwclient.page.Page'] = None
    page_info: Mapping[str, Any] = field(default_factory=dict, repr=False)

    @property
    def link(self) -> str:
        """Alias for :attr:`original`."""
        return self.original

    @property
    def requested_title(self) -> str:
        """Alias for :attr:`title`."""
        return self.title

    @property
    def requested_fragment(self) -> Optional[str]:
        """Alias for :attr:`fragment`."""
        return self.fragment

    @property
    def ok(self) -> bool:
        """Whether a single section was resolved successfully."""
        return self.status in RESOLVED_STATUSES

    @property
    def resolved(self) -> bool:
        """Whether a single section was resolved successfully."""
        return self.ok

    @property
    def section_deleted(self) -> bool:
        """Whether the target page exists but the requested section does not."""
        return self.status == STATUS_SECTION_DELETED

    @property
    def section_unavailable(self) -> bool:
        """Whether the section index could not be read."""
        return self.status == STATUS_SECTION_UNAVAILABLE

    @property
    def ambiguous(self) -> bool:
        """Whether several sections share the requested heading."""
        return self.status == STATUS_SECTION_AMBIGUOUS

    @property
    def redirect_loop(self) -> bool:
        """Whether following redirects formed a cycle."""
        return self.status == STATUS_REDIRECT_LOOP

    @property
    def numbered(self) -> bool:
        """Whether a repeated heading was selected via its numbered anchor."""
        return self.status == STATUS_SECTION_NUMBERED

    @property
    def duplicate_number(self) -> Optional[int]:
        """Numeric suffix of a repeated heading selected by the link."""
        return self.section.duplicate_number if self.section else None

    @property
    def target(self) -> Optional[str]:
        """The resolved target in ``title#fragment`` form, if known."""
        if self.target_title is None:
            return None
        if self.target_fragment:
            return f'{self.target_title}#{self.target_fragment}'
        return self.target_title

    @property
    def section_index(self) -> Optional[int]:
        """The section index passed to :meth:`mwclient.page.Page.text`."""
        return self.section.index if self.section is not None else None

    def path(self) -> List[Tuple[str, Optional[str]]]:
        """Return ``(title, fragment)`` pairs in the order they were visited.

        The first element is the original link and the last element is the
        resolved target.  Fragments are included because a redirect may change
        the section without changing the page.
        """
        path: List[Tuple[str, Optional[str]]] = [(self.title, self.fragment)]
        fragment = self.fragment
        for hop in self.chain:
            fragment = hop.to_fragment if hop.to_fragment is not None else fragment
            path.append((hop.to_title, fragment))
        if not self.chain and self.target_title is not None:
            path = [(self.target_title, self.target_fragment)]
        return path


class LinkResolver:
    """Resolve legacy page links and extract the referenced section.

    Args:
        site: The :class:`mwclient.client.Site` to query.
        max_redirects: Safety limit for the number of redirect hops followed.

    Examples:
        >>> resolver = LinkResolver(site)
        >>> result = resolver.resolve('Old name#Material')
        >>> result.status
        'resolved'
        >>> result.target_title, result.target_fragment
        ('New entry', 'Material')
        >>> result.text
        '== Material ==\\n...'
    """

    def __init__(self, site: 'mwclient.client.Site', max_redirects: int = 50) -> None:
        self.site = site
        self.max_redirects = max_redirects
        self._sections_cache: Dict[str, Tuple[Section, ...]] = {}
        self._page_cache: Dict[str, 'mwclient.page.Page'] = {}

    # Public API ---------------------------------------------------------
    def resolve(
        self,
        link: str,
        include_text: bool = True,
    ) -> ResolvedLink:
        """Resolve one legacy link.

        Args:
            link: A link such as ``Old name#Material``, ``[[Old name#Material]]``
                or the same with a display-text pipe.  The value is retained
                verbatim in :attr:`ResolvedLink.original`.
            include_text: Fetch the wikitext of the referenced section.  When
                the target heading is ambiguous, every candidate section is
                fetched.

        Returns:
            ResolvedLink: The resolved target and, where possible, its section
                wikitext.
        """
        original = link
        title, fragment, parse_error = self._parse_link(link)
        if parse_error is not None:
            return ResolvedLink(
                original=original, title=title, fragment=fragment,
                target_title=None, target_fragment=None,
                status=STATUS_INVALID, reason=parse_error,
            )

        follow = self._follow_redirects(title, fragment)
        chain = follow['chain']
        if follow['status'] is not None:
            return ResolvedLink(
                original=original,
                title=title,
                fragment=fragment,
                target_title=follow['title'],
                target_fragment=follow['fragment'],
                status=follow['status'],
                chain=chain,
                cycle=follow['cycle'],
                reason=follow['reason'],
                page=follow['page'],
                page_info=follow['page_info'],
            )

        target_title = follow['title']
        target_fragment = follow['fragment']
        page = follow['page']
        page_info = follow['page_info']

        if target_fragment is None:
            text, text_error = self._read_text(page, None) if include_text \
                else (None, None)
            return ResolvedLink(
                original=original, title=title, fragment=fragment,
                target_title=target_title, target_fragment=None,
                status=STATUS_RESOLVED, chain=chain, text=text,
                text_error=text_error, page=page, page_info=page_info,
            )

        try:
            sections = self._get_sections(target_title)
        except mwclient.errors.APIError as error:
            return ResolvedLink(
                original=original, title=title, fragment=fragment,
                target_title=target_title, target_fragment=target_fragment,
                status=STATUS_SECTION_UNAVAILABLE, chain=chain,
                reason=(f"The section index for '{target_title}' could not be "
                        f'read: {error.info}'),
                page=page, page_info=page_info,
            )
        match = self._match_section(sections, target_fragment, target_title)

        if match['status'] == STATUS_SECTION_DELETED:
            return ResolvedLink(
                original=original, title=title, fragment=fragment,
                target_title=target_title, target_fragment=target_fragment,
                status=STATUS_SECTION_DELETED, chain=chain,
                reason=match['reason'], page=page, page_info=page_info,
            )

        if match['status'] == STATUS_SECTION_AMBIGUOUS:
            candidates = match['candidates']
            texts: Tuple[str, ...] = ()
            text_error: Optional[str] = None
            if include_text:
                collected = []
                for candidate in candidates:
                    candidate_text, candidate_error = self._read_text(
                        page, candidate.index
                    )
                    if candidate_error is not None:
                        text_error = candidate_error
                    collected.append(candidate_text or '')
                texts = tuple(collected)
            return ResolvedLink(
                original=original, title=title, fragment=fragment,
                target_title=target_title, target_fragment=target_fragment,
                status=STATUS_SECTION_AMBIGUOUS, chain=chain,
                candidates=candidates, texts=texts, text_error=text_error,
                reason=match['reason'], page=page, page_info=page_info,
            )

        selected = match['section']
        text, text_error = self._read_text(page, selected.index) \
            if include_text else (None, None)
        return ResolvedLink(
            original=original, title=title, fragment=fragment,
            target_title=target_title, target_fragment=target_fragment,
            status=match['status'], chain=chain, section=selected,
            text=text, text_error=text_error, page=page, page_info=page_info,
        )

    def resolve_many(
        self, links: Iterable[str], include_text: bool = True
    ) -> List[ResolvedLink]:
        """Resolve several links, returning results in input order."""
        return [self.resolve(link, include_text=include_text) for link in links]

    def sections(self, title: str) -> Tuple[Section, ...]:
        """Return the section index for ``title``, following redirects."""
        follow = self._follow_redirects(title, None)
        if follow['status'] is not None:
            return ()
        try:
            return self._get_sections(follow['title'])
        except mwclient.errors.APIError:
            return ()

    # Link parsing -------------------------------------------------------
    @staticmethod
    def _parse_link(link: str) -> Tuple[str, Optional[str], Optional[str]]:
        value = link.strip()
        if not value:
            return '', None, 'The link is empty'

        if value.startswith('[[') and value.endswith(']]'):
            value = value[2:-2].strip()
        # Display text is not part of the target.
        if '|' in value:
            value = value.split('|', 1)[0].strip()

        if _EXTERNAL_RE.match(value) or value.startswith('//'):
            return value, None, 'External links are not supported'

        title, has_fragment, raw_fragment = value.partition('#')
        title = unquote(title).strip()
        if title.startswith(':'):
            title = title[1:].strip()
        if not title:
            return title, _decode_fragment(raw_fragment) if has_fragment else None, \
                'The link does not contain a page title'

        fragment = _decode_fragment(raw_fragment) if has_fragment else None
        return title, fragment, None

    # Redirect handling --------------------------------------------------
    def _query_info(self, title: str) -> Mapping[str, Any]:
        data = self.site.get(
            'query', prop='info', titles=title, redirects=''
        )
        return data.get('query', {})

    def _follow_redirects(
        self, title: str, fragment: Optional[str]
    ) -> Dict[str, Any]:
        current_title = title
        current_fragment = fragment
        redirect_map: Dict[str, Mapping[str, Any]] = {}
        pages: Dict[str, Mapping[str, Any]] = {}
        chain: List[RedirectHop] = []
        seen_titles: List[str] = [title]
        seen_states = {(self._title_key(title), self._fragment_key(fragment))}
        queries_done = 0
        latest_page: Optional[Mapping[str, Any]] = None

        while True:
            known_page = pages.get(self._title_key(current_title))
            needs_query = (
                self._title_key(current_title) not in redirect_map
                and not (known_page is not None and 'redirect' not in known_page)
            )
            if needs_query:
                if queries_done >= self.max_redirects:
                    return self._follow_result(
                        current_title, current_fragment, chain, [],
                        STATUS_REDIRECT_UNRESOLVED,
                        f'Exceeded {self.max_redirects} redirect hops',
                        None, pages,
                    )
                query = self._query_info(current_title)
                queries_done += 1

                # MediaWiki may return a normalized title before listing the
                # redirect under its canonical name.
                canonical = self._normalized_title(query, current_title)
                if canonical != current_title:
                    current_title = canonical
                    seen_titles[-1] = canonical
                    seen_states.add(
                        (self._title_key(canonical),
                         self._fragment_key(current_fragment))
                    )

                for page in query.get('pages', {}).values():
                    pages[self._title_key(str(page.get('title', '')))] = page
                latest_page = self._select_page(
                    query.get('pages', {}), current_title
                )
                if latest_page is not None and 'invalid' in latest_page:
                    return self._follow_result(
                        current_title, current_fragment, chain, [],
                        STATUS_INVALID,
                        latest_page.get('invalidreason')
                        or f"'{current_title}' is not a valid page title",
                        None, pages,
                    )
                for hop in query.get('redirects', ()):
                    from_title = str(hop.get('from', ''))
                    key = self._title_key(from_title)
                    if key not in redirect_map:
                        redirect_map[key] = hop

            hop = redirect_map.get(self._title_key(current_title))
            if hop is None:
                page = pages.get(self._title_key(current_title), latest_page)
                if page is None:
                    page = self._select_page({}, current_title)

                if page is not None and 'redirect' in page:
                    # The API did not expose the target (for example because
                    # it detected a loop).  Read the redirect source itself
                    # so that the cycle can still be reported precisely.
                    content_target = self._redirect_from_content(current_title, page)
                    if content_target is None:
                        return self._follow_result(
                            current_title, current_fragment, chain, [],
                            STATUS_REDIRECT_UNRESOLVED,
                            'The page is a redirect but no target could be read',
                            page, pages,
                        )
                    hop = {
                        'from': current_title,
                        'to': content_target[0],
                        'tofragment': content_target[1],
                    }
                    redirect_map[self._title_key(current_title)] = hop

            if hop is None:
                page = pages.get(self._title_key(current_title), latest_page)
                if page is None:
                    page = self._select_page({}, current_title)
                if page is not None and 'missing' in page:
                    return self._follow_result(
                        current_title, current_fragment, chain, [],
                        STATUS_PAGE_MISSING,
                        f"The page '{current_title}' does not exist",
                        page, pages,
                    )
                if page is None:
                    return self._follow_result(
                        current_title, current_fragment, chain, [],
                        STATUS_PAGE_MISSING,
                        f"No information was returned for '{current_title}'",
                        None, pages,
                    )
                return self._follow_result(
                    current_title, current_fragment, chain, [],
                    None, None, page, pages,
                )

            from_title = str(hop.get('from', current_title))
            to_title_value = str(hop.get('to', ''))
            to_title, embedded_fragment = self._split_target(to_title_value)
            if not to_title:
                return self._follow_result(
                    current_title, current_fragment, chain, [],
                    STATUS_REDIRECT_UNRESOLVED,
                    f"The redirect '{from_title}' has no target",
                    latest_page, pages,
                )

            explicit_fragment = None
            if 'tofragment' in hop:
                explicit_fragment = _decode_fragment(hop.get('tofragment'))
            if explicit_fragment is None:
                explicit_fragment = embedded_fragment

            if explicit_fragment is not None:
                next_fragment = explicit_fragment
            else:
                next_fragment = current_fragment

            chain.append(RedirectHop(
                from_title=from_title,
                to_title=to_title,
                to_fragment=explicit_fragment,
            ))

            state = (self._title_key(to_title), self._fragment_key(next_fragment))
            if state in seen_states:
                cycle = self._cycle_titles(seen_titles, to_title)
                return self._follow_result(
                    to_title, next_fragment, chain, cycle,
                    STATUS_REDIRECT_LOOP,
                    self._format_cycle(cycle, next_fragment),
                    pages.get(self._title_key(to_title), latest_page), pages,
                )

            seen_states.add(state)
            seen_titles.append(to_title)
            current_title = to_title
            current_fragment = next_fragment

            if len(chain) > self.max_redirects:
                return self._follow_result(
                    current_title, current_fragment, chain, [],
                    STATUS_REDIRECT_UNRESOLVED,
                    f'Exceeded {self.max_redirects} redirect hops',
                    pages.get(self._title_key(current_title), latest_page), pages,
                )

    def _follow_result(
        self,
        title: str,
        fragment: Optional[str],
        chain: List[RedirectHop],
        cycle: List[str],
        status: Optional[str],
        reason: Optional[str],
        page: Optional[Mapping[str, Any]],
        pages: Mapping[str, Mapping[str, Any]],
    ) -> Dict[str, Any]:
        # Prefer the canonical title returned by the API for the target page.
        canonical_title = title
        if page is not None and page.get('title'):
            canonical_title = str(page['title'])
        page_obj = None
        if status is None:
            info = dict(page) if page is not None else None
            page_obj = self._make_page(canonical_title, info)
        return {
            'title': canonical_title,
            'fragment': fragment,
            'chain': tuple(chain),
            'cycle': tuple(cycle),
            'status': status,
            'reason': reason,
            'page': page_obj,
            'page_info': dict(page) if page is not None else {},
        }

    @staticmethod
    def _select_page(
        pages: Mapping[str, Any], title: str
    ) -> Optional[Mapping[str, Any]]:
        if not pages:
            return None
        key = _normalize_title(title)
        for page in pages.values():
            if _normalize_title(str(page.get('title', ''))) == key:
                return page
        if len(pages) == 1:
            return next(iter(pages.values()))
        return None

    @staticmethod
    def _normalized_title(query: Mapping[str, Any], title: str) -> str:
        key = _normalize_title(title)
        for entry in query.get('normalized', ()):
            if _normalize_title(str(entry.get('from', ''))) == key:
                return str(entry.get('to', title))
        for entry in query.get('redirects', ()):
            from_title = str(entry.get('from', ''))
            if _normalize_title(from_title) == key:
                return from_title
        return title

    def _redirect_from_content(
        self, title: str, info: Optional[Mapping[str, Any]]
    ) -> Optional[Tuple[str, Optional[str]]]:
        page = mwclient.page.Page(self.site, title, info=info)
        try:
            text = page.text(cache=False)
        except (mwclient.errors.MwClientError, OSError):
            return None
        match = _REDIRECT_RE.match(text)
        if not match:
            return None
        target_title = match.group(1).strip()
        if target_title.startswith(':'):
            target_title = target_title[1:].strip()
        target_fragment = _decode_fragment(match.group(2))
        if not target_title:
            return None
        return target_title, target_fragment

    @staticmethod
    def _split_target(value: str) -> Tuple[str, Optional[str]]:
        title, has_fragment, fragment = value.partition('#')
        return title.strip(), _decode_fragment(fragment) if has_fragment else None

    @staticmethod
    def _cycle_titles(seen: List[str], repeated: str) -> List[str]:
        key = _normalize_title(repeated)
        for index, title in enumerate(seen):
            if _normalize_title(title) == key:
                return seen[index:] + [repeated]
        return [repeated]

    @staticmethod
    def _format_cycle(cycle: List[str], fragment: Optional[str]) -> str:
        suffix = f'#{fragment}' if fragment else ''
        if not cycle:
            return 'Redirect cycle detected'
        return 'Redirect cycle: ' + ' -> '.join(cycle) + suffix

    @staticmethod
    def _title_key(title: str) -> str:
        return _normalize_title(title)

    @staticmethod
    def _fragment_key(fragment: Optional[str]) -> str:
        return _clean(fragment)

    # Section handling ---------------------------------------------------
    def _get_sections(self, title: str) -> Tuple[Section, ...]:
        """Return the section index, raising if it cannot be read."""
        key = self._title_key(title)
        if key in self._sections_cache:
            return self._sections_cache[key]

        raw_sections: Iterable[Mapping[str, Any]] = ()
        try:
            data = self.site.get('parse', page=title, prop='sections')
            raw_sections = data.get('parse', {}).get('sections', ())
        except mwclient.errors.APIError as error:
            # Older MediaWiki versions or restricted wikis may not allow the
            # parse action.  Fall back to the wikitext headings so that a
            # transient API refusal is not reported as a deleted section.
            raw_sections = self._headings_from_text(title)
            if not raw_sections:
                # The fallback could not read the page either: report that the
                # section index is unavailable rather than "section deleted".
                raise error from error

        sections = [
            self._section_from_api(title, raw) for raw in raw_sections
        ]
        counts: Dict[str, int] = {}
        for section in sections:
            normalized = _clean(section.heading)
            counts[normalized] = counts.get(normalized, 0) + 1

        # MediaWiki derives canonical anchors from headings and appends a
        # numeric suffix for repeats.  When the API omits ``anchor`` (older
        # releases), derive the same sequence locally, taking care not to
        # collide with a heading that is literally called "Material 2".
        derived: List[str] = []
        used = {
            _clean(section.anchor) for section in sections if section.anchor
        }
        for section in sections:
            if section.anchor:
                derived.append(section.anchor)
                continue
            base = _slugify(section.heading)
            candidate = base
            suffix = 2
            while _clean(candidate) in used:
                candidate = f'{base}_{suffix}'
                suffix += 1
            used.add(_clean(candidate))
            derived.append(candidate)

        augmented: List[Section] = []
        hierarchy: List[Tuple[int, str]] = []
        for section, anchor in zip(sections, derived):
            while hierarchy and hierarchy[-1][0] >= section.level:
                hierarchy.pop()
            parents = tuple(heading for _, heading in hierarchy)
            hierarchy.append((section.level, section.heading))
            count = counts.get(_clean(section.heading), 1)
            duplicate_number = None
            if count > 1:
                match = _DUPLICATE_SUFFIX_RE.search(anchor)
                if match:
                    duplicate_number = int(match.group('number'))
            augmented.append(Section(
                page_title=section.page_title,
                index=section.index,
                heading=section.heading,
                anchor=anchor,
                level=section.level,
                toclevel=section.toclevel,
                number=section.number,
                byteoffset=section.byteoffset,
                duplicate_number=duplicate_number,
                duplicate_count=count,
                parents=parents,
            ))

        result = tuple(augmented)
        self._sections_cache[key] = result
        return result

    def _headings_from_text(self, title: str) -> List[Mapping[str, Any]]:
        page = self._make_page(title, None)
        try:
            text = page.text(cache=False)
        except (mwclient.errors.MwClientError, OSError):
            return []

        headings: List[Mapping[str, Any]] = []
        for match in _HEADING_RE.finditer(text):
            level = len(match.group(1))
            heading = match.group(2).strip()
            if not heading:
                continue
            headings.append({
                'line': heading,
                'level': str(level),
                'toclevel': max(1, level - 1),
                'index': str(len(headings) + 1),
                'anchor': _slugify(heading),
                'byteoffset': str(match.start()),
            })
        return headings

    @staticmethod
    def _section_from_api(title: str, raw: Mapping[str, Any]) -> Section:
        index_value = raw.get('index', 0)
        try:
            index = int(index_value)
        except (TypeError, ValueError):
            index = 0
        try:
            level = int(raw.get('level', 0) or 0)
        except (TypeError, ValueError):
            level = 0
        try:
            toclevel = int(raw.get('toclevel', 0) or 0)
        except (TypeError, ValueError):
            toclevel = 0
        byteoffset = raw.get('byteoffset')
        if byteoffset is not None:
            try:
                byteoffset = int(byteoffset)
            except (TypeError, ValueError):
                byteoffset = None
        return Section(
            page_title=title,
            index=index,
            heading=str(raw.get('line', '')),
            anchor=str(raw.get('anchor', '')),
            level=level,
            toclevel=toclevel,
            number=str(raw['number']) if raw.get('number') is not None else None,
            byteoffset=byteoffset,
        )

    @staticmethod
    def _match_section(
        sections: Tuple[Section, ...], fragment: str, page_title: str = ''
    ) -> Dict[str, Any]:
        if _clean(fragment).casefold() == 'top':
            return {
                'status': STATUS_RESOLVED,
                'section': Section(
                    page_title=page_title,
                    index=0,
                    heading='',
                    anchor='top',
                ),
            }

        fragment_key = _clean(fragment)
        fragment_folded = fragment_key.casefold()

        # Canonical anchors are matched first and case-sensitively, so a
        # numbered duplicate is never confused with the first occurrence.
        exact = [
            section for section in sections
            if _clean(section.anchor) == fragment_key
        ]
        if not exact:
            exact = [
                section for section in sections
                if _clean(section.anchor).casefold() == fragment_folded
            ]
        if not exact:
            # Links may use the displayed heading instead of the canonical
            # anchor (for example a heading containing punctuation).
            exact = [
                section for section in sections
                if _clean(section.heading) == fragment_key
            ]
        if not exact:
            exact = [
                section for section in sections
                if _clean(section.heading).casefold() == fragment_folded
            ]

        if not exact:
            return {
                'status': STATUS_SECTION_DELETED,
                'reason': f"No section matches '{fragment}'",
            }

        if len(exact) == 1:
            section = exact[0]
            if section.duplicate_count > 1:
                if section.duplicate_number is not None:
                    return {
                        'status': STATUS_SECTION_NUMBERED,
                        'section': section,
                    }
                return {
                    'status': STATUS_SECTION_AMBIGUOUS,
                    'candidates': LinkResolver._duplicate_group(
                        sections, section
                    ),
                    'reason': (
                        f"{section.duplicate_count} sections are titled "
                        f"'{section.heading}'; the link does not select a "
                        'numbered anchor'
                    ),
                }
            return {'status': STATUS_RESOLVED, 'section': section}

        return {
            'status': STATUS_SECTION_AMBIGUOUS,
            'candidates': tuple(exact),
            'reason': (
                f"Several sections match '{fragment}': "
                + ', '.join(section.anchor for section in exact)
            ),
        }

    @staticmethod
    def _duplicate_group(
        sections: Tuple[Section, ...], selected: Section
    ) -> Tuple[Section, ...]:
        key = _clean(selected.heading)
        return tuple(
            section for section in sections
            if _clean(section.heading) == key
        )

    # Page/text helpers --------------------------------------------------
    def _make_page(
        self, title: str, info: Optional[Mapping[str, Any]]
    ) -> 'mwclient.page.Page':
        key = self._title_key(title)
        if key in self._page_cache:
            return self._page_cache[key]
        page = mwclient.page.Page(self.site, title, info=info)
        self._page_cache[key] = page
        return page

    def _page_text(
        self, page: Optional['mwclient.page.Page'], section: Optional[int]
    ) -> str:
        if page is None:
            return ''
        if section is None:
            return page.text()
        return page.text(section=section)

    def _read_text(
        self, page: Optional['mwclient.page.Page'], section: Optional[int]
    ) -> Tuple[Optional[str], Optional[str]]:
        """Read text without turning a fetch error into empty content."""
        try:
            return self._page_text(page, section), None
        except mwclient.errors.APIError as error:
            code = error.code or ''
            info = error.info or ''
            return None, f'{code}: {info}' if code else info or str(error)
        except mwclient.errors.MwClientError as error:
            return None, str(error)
        except OSError as error:
            return None, str(error)


def resolve_link(
    site: 'mwclient.client.Site',
    link: str,
    include_text: bool = True,
) -> ResolvedLink:
    """Resolve one legacy link using a fresh :class:`LinkResolver`."""
    return LinkResolver(site).resolve(link, include_text=include_text)


def resolve_links(
    site: 'mwclient.client.Site',
    links: Iterable[str],
    include_text: bool = True,
) -> List[ResolvedLink]:
    """Resolve several links using one shared :class:`LinkResolver`."""
    return LinkResolver(site).resolve_many(links, include_text=include_text)
